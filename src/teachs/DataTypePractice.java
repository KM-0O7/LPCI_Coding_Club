package teachs;

public class DataTypePractice {

	/**
	 * @param args unused
	 */
	public static void main(String[] args) {
		
		//Integers
		String somethingLike = "Austin";
		System.out.println(somethingLike);
		/*
		 * Block Comment
		 */
		
		int num = 0;
		//0, 1, 2, 3, 4, 5 ...
		
		double decimal = 0.5;
		
		float num2 = 0.5f;
		//0.1, 0.3333, 3.14, -1.24 ...
		
		boolean val = true;
		//true, false
		
		String name = "Wiggle";
		//any sentence
		
		char a = 'a';
		//single character
		
		/*---- NAMING CONVENTIONS ----
		 * camelCase: ryanEng, austinWalton, jamesLeungGrandma
		 * PascalCase: RyanEng, AustinWalton, JamesLeungGrandma
		 */
		
		/* ---- PRINTING ---- 
		 * Outputs to the console
		 */
		
		//System.out.print(name);
		System.out.println("My name is: " + name);
	}
}
